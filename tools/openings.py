"""Complete opening seeds with Stockfish and keep the balanced ones.

Each seed is a short UCI opening line. Missing plies are filled with Stockfish's
best move at a fixed depth, then the final position is evaluated by Stockfish
(from White's point of view). Lines whose evaluation falls outside ``--cp-limit``
are dropped; the rest are written as a match opening set.

    python -m tools.openings --stockfish /usr/games/stockfish \
        --seeds openings/seeds.txt --out data/openings/acemi-64.txt

Tools-only: python-chess and Stockfish. The engine package is not involved.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

import chess
import chess.engine


def parse_seeds(path: Path) -> list[tuple[str, list[str]]]:
    seeds: list[tuple[str, list[str]]] = []
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "|" not in line:
            raise ValueError(f"{path}:{number}: expected '<name> | <UCI moves>'")
        name, moves_text = (part.strip() for part in line.split("|", 1))
        moves = moves_text.split()
        board = chess.Board()
        for move in moves:
            try:
                board.push_uci(move)
            except ValueError as error:
                raise ValueError(f"{path}:{number}: illegal move {move!r}") from error
        seeds.append((name, moves))
    if not seeds:
        raise ValueError(f"{path}: no seeds found")
    return seeds


def complete_line(
    seed: list[str], evaluator, target_plies: int, depth: int = 12
) -> list[str]:
    """Extend (or truncate) a seed to exactly ``target_plies`` half-moves."""
    if len(seed) >= target_plies:
        return list(seed[:target_plies])
    board = chess.Board()
    for move in seed:
        board.push_uci(move)
    line = list(seed)
    while len(line) < target_plies:
        move = evaluator.best_move(board, depth)
        if move is None:
            raise ValueError(f"engine returned no move for {board.fen()}")
        board.push(move)
        line.append(move.uci())
    return line


def build_openings(
    seeds: list[tuple[str, list[str]]],
    evaluator,
    out_path: Path,
    *,
    target_plies: int = 10,
    cp_limit: int = 50,
    max_lines: int = 64,
    extend_depth: int = 12,
    eval_depth: int = 14,
) -> list[tuple[str, list[str], int]]:
    """Complete, evaluate and filter the seeds; write the accepted lines."""
    accepted: list[tuple[str, list[str], int]] = []
    seen: set[tuple[str, ...]] = set()
    for name, seed in seeds:
        line = complete_line(seed, evaluator, target_plies, depth=extend_depth)
        key = tuple(line)
        if key in seen:
            print(f"skip  {name}: duplicate line")
            continue
        board = chess.Board()
        for move in line:
            board.push_uci(move)
        score = evaluator.score_cp(board, eval_depth)
        if score is None:
            print(f"drop  {name}: mate score")
            continue
        if abs(score) > cp_limit:
            print(f"drop  {name}: {score:+d} cp outside +-{cp_limit}")
            continue
        seen.add(key)
        accepted.append((name, line, score))
        print(f"keep  {name}: {score:+d} cp")
        if len(accepted) >= max_lines:
            break
    write_openings(out_path, accepted)
    return accepted


def write_openings(path: Path, accepted: list[tuple[str, list[str], int]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Generated by tools/openings.py from openings/seeds.txt; Stockfish-extended and balanced.",
        "# One opening per line; each line is played with both colours by tools.match.",
        "",
    ]
    for name, moves, score in accepted:
        lines.append(f"# {name} ({score:+d} cp, White's view)")
        lines.append(" ".join(moves))
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


class StockfishEvaluator:
    def __init__(self, path: str) -> None:
        self.engine = chess.engine.SimpleEngine.popen_uci(path)
        self.engine.configure({"Threads": 1, "Hash": 64})

    def best_move(self, board: chess.Board, depth: int) -> chess.Move | None:
        result = self.engine.play(board, chess.engine.Limit(depth=depth))
        return result.move

    def score_cp(self, board: chess.Board, depth: int) -> int | None:
        info = self.engine.analyse(board, chess.engine.Limit(depth=depth))
        score = info.get("score")
        if score is None:
            return None
        white = score.pov(chess.WHITE)
        if white.is_mate():
            return None
        return white.score()

    def close(self) -> None:
        self.engine.quit()


def find_stockfish(explicit: str | None) -> str:
    if explicit:
        return explicit
    for candidate in ("stockfish", "/usr/games/stockfish", "/usr/bin/stockfish", "/usr/local/bin/stockfish"):
        found = shutil.which(candidate) if not candidate.startswith("/") else candidate
        if found and Path(found).exists():
            return found
    raise FileNotFoundError("Stockfish not found; pass --stockfish PATH")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build a Stockfish-balanced opening set from seeds.")
    parser.add_argument("--seeds", type=Path, default=Path("openings/seeds.txt"))
    parser.add_argument("--out", type=Path, default=Path("data/openings/acemi-64.txt"))
    parser.add_argument("--stockfish", default=None)
    parser.add_argument("--plies", type=int, default=10)
    parser.add_argument("--extend-depth", type=int, default=12)
    parser.add_argument("--eval-depth", type=int, default=14)
    parser.add_argument("--cp-limit", type=int, default=50)
    parser.add_argument("--max", type=int, default=64)
    args = parser.parse_args(argv)

    seeds = parse_seeds(args.seeds)
    print(f"seeds: {len(seeds)}")
    evaluator = StockfishEvaluator(find_stockfish(args.stockfish))
    try:
        accepted = build_openings(
            seeds,
            evaluator,
            args.out,
            target_plies=args.plies,
            cp_limit=args.cp_limit,
            max_lines=args.max,
            extend_depth=args.extend_depth,
            eval_depth=args.eval_depth,
        )
    finally:
        evaluator.close()
    print(f"accepted: {len(accepted)} / {args.max}")
    if len(accepted) < args.max:
        print("warning: fewer lines than requested; add seeds or relax --cp-limit")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
