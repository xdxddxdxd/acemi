"""Polyglot opening book reader.

The engine key is computed from the engine's own 0x88 board; the random table is
the standard Polyglot one, so any book generated by common tools can be read.
"""

from __future__ import annotations

import random
import struct
from pathlib import Path

from engine.board import (
    BLACK_KING_SIDE,
    BLACK_QUEEN_SIDE,
    BISHOP,
    KING,
    KNIGHT,
    PAWN,
    QUEEN,
    ROOK,
    WHITE,
    WHITE_KING_SIDE,
    WHITE_QUEEN_SIDE,
    Board,
    Move,
    is_valid_square,
)
from engine.movegen import generate_legal_moves
from engine.polyglot_keys import POLYGLOT_RANDOM_ARRAY

_CASTLING_INDEX = (
    (WHITE_KING_SIDE, 768),
    (WHITE_QUEEN_SIDE, 769),
    (BLACK_KING_SIDE, 770),
    (BLACK_QUEEN_SIDE, 771),
)
_PROMOTION = {1: KNIGHT, 2: BISHOP, 3: ROOK, 4: QUEEN}


def _polyglot_square(square: int) -> int:
    # 0x88 row 0 is rank 8; Polyglot numbers a1=0 .. h8=63.
    return (7 - (square >> 4)) * 8 + (square & 7)


def polyglot_hash(board: Board) -> int:
    """Standard Polyglot Zobrist hash of the position."""
    value = 0
    for piece, squares in board.piece_squares.items():
        if not squares:
            continue
        index = (abs(piece) - 1) * 2 + (1 if piece > 0 else 0)
        base = 64 * index
        for square in squares:
            value ^= POLYGLOT_RANDOM_ARRAY[base + _polyglot_square(square)]

    for right, index in _CASTLING_INDEX:
        if board.castling_rights & right:
            value ^= POLYGLOT_RANDOM_ARRAY[index]

    ep_square = board.en_passant_square
    if ep_square is not None:
        file = ep_square & 7
        row = ep_square >> 4
        pawn = PAWN if board.side_to_move == WHITE else -PAWN
        step = 1 if board.side_to_move == WHITE else -1
        candidates = (row + step) * 16 + file - 1, (row + step) * 16 + file + 1
        if any(
            is_valid_square(square) and board.squares[square] == pawn
            for square in candidates
        ):
            value ^= POLYGLOT_RANDOM_ARRAY[772 + file]

    if board.side_to_move == WHITE:
        value ^= POLYGLOT_RANDOM_ARRAY[780]
    return value


class PolyglotBook:
    """A read-only Polyglot book keyed by the standard position hash."""

    def __init__(self, path: str | Path) -> None:
        data = Path(path).read_bytes()
        if len(data) % 16:
            raise ValueError(f"{path}: Polyglot books are a sequence of 16-byte entries")
        entries: dict[int, list[tuple[int, int]]] = {}
        for offset in range(0, len(data), 16):
            key, move, weight, _learn = struct.unpack_from(">QHHI", data, offset)
            if key == 0 and move == 0 and weight == 0:
                continue
            entries.setdefault(key, []).append((move, weight))
        self.entries = entries

    def __len__(self) -> int:
        return sum(len(moves) for moves in self.entries.values())

    def find_move(self, board: Board, rng: random.Random | None = None) -> Move | None:
        raw_moves = self.entries.get(polyglot_hash(board))
        if not raw_moves:
            return None
        legal = {move.uci(): move for move in generate_legal_moves(board)}
        candidates: list[tuple[Move, int]] = []
        for code, weight in raw_moves:
            decoded = self._decode_move(board, code)
            if decoded is None:
                continue
            move = legal.get(decoded.uci())
            if move is not None:
                candidates.append((move, max(0, weight)))
        if not candidates:
            return None
        if rng is None:
            return max(candidates, key=lambda item: item[1])[0]
        total = sum(weight for _move, weight in candidates)
        if total == 0:
            return candidates[0][0]
        pick = rng.uniform(0, total)
        for move, weight in candidates:
            pick -= weight
            if pick <= 0:
                return move
        return candidates[-1][0]

    @staticmethod
    def _decode_move(board: Board, code: int) -> Move | None:
        to_file = code & 7
        to_rank = (code >> 3) & 7
        from_file = (code >> 6) & 7
        from_rank = (code >> 9) & 7
        promotion = (code >> 12) & 7
        from_square = (7 - from_rank) * 16 + from_file
        to_square = (7 - to_rank) * 16 + to_file
        if not is_valid_square(from_square) or not is_valid_square(to_square):
            return None
        piece = board.squares[from_square]
        target = board.squares[to_square]
        if abs(piece) == KING and target != 0 and abs(target) == ROOK and (target > 0) == (piece > 0):
            # Polyglot stores castling as the king capturing its own rook.
            to_square = (7 - to_rank) * 16 + (6 if to_file > from_file else 2)
        return Move(from_square, to_square, _PROMOTION.get(promotion))
